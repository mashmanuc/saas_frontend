/**
 * Режим показу (LAW §9 v1.56, власник 2026-10-25: «якби було за замовчуванням на цілий екран, щоб при переході
 * на наступну сторінку не прийшлось би клацати на цілий екран… оце чорненьке меню картинки треба приховувати»).
 *
 * Вмикає його «На весь екран» з пульта для картинки чи документа (`useRemoteViewAdapter.focusObject`). Поки він
 * увімкнений:
 *   - «Далі» / «Назад» / дотик у «Сценарії» відкривають нову сторінку одразу з її головною картинкою (найбільшою)
 *     на весь екран; сторінка без картинки — уся сторінка на весь екран;
 *   - перемкнути пульт на мелодію (щоб «Грати») не знімає повного екрана; інша картинка — стає на весь екран;
 *   - на ноутбуці сховано те, що на проєкторі заважає: рамку й чорне меню виділеного об'єкта, смуги прокрутки
 *     аркуша, кружечок Інтегралика з його підказками.
 * Вимикає «Уся сторінка» на пульті (і все, що й раніше знімало показ: ✍, «Задача на екран», «Згорнути» об'єкта
 * на весь екран). Лише вигляд цього екрана: без ops, Replay, запису й мережі (як `view.fit` v1.2).
 */
import { reactive } from 'vue'

export const SHOW_MODE_BODY_CLASS = 'wb-show-mode'

/** Реактивне: WBCanvas, аркуш і кружечок Інтегралика читають його, щоб сховати своє. */
export const showMode = reactive<{ active: boolean }>({ active: false })

export function setShowMode(on: boolean): void {
  if (showMode.active === on) return
  showMode.active = on
  // Кружечок Інтегралика живе поза дошкою (CommandPalette) — йому досить класу на <body>.
  if (typeof document !== 'undefined') document.body.classList.toggle(SHOW_MODE_BODY_CLASS, on)
}
