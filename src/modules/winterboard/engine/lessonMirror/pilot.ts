/**
 * Пілот «Дзеркала уроку» — лише контрольні акаунти власника (ТЗ §2): 40 і 220 (урок 09.10 вів 220).
 *
 * З 2026-10-16 гейт лише для кнопки «🎬 Відео» на КОЖНІЙ картці «Моїх записів» і підказки над
 * списком: список не знає, у яких записах є знімки Дзеркала, тож для решти вчителів кнопка здебільшого
 * вела б у відмову «немає знімків». На сторінці запису (WBPublicView) «Створити відеофрагмент» —
 * усім власникам запису, і лише коли в записі справді є знімки.
 */
export const MIRROR_CLIP_PILOT_USER_IDS: ReadonlySet<number> = new Set([40, 220])

export function isMirrorClipPilotUser(userId: unknown): boolean {
  return MIRROR_CLIP_PILOT_USER_IDS.has(Number(userId))
}
