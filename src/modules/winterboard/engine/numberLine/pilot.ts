/**
 * Повна числова пряма — «Знаки інтервалів» (метод інтервалів) і точний розвʼязок на сервері — для
 * ВСІХ, хто увійшов (власник 2026-10-14: «треба, щоб вже для всіх користувачів було увімкнено»).
 * До того (2026-10-13) — лише контрольний акаунт власника id 40.
 *
 * Гість локальної дошки (без акаунта) — лише рушій на сторінці: сервер розвʼязувача вимагає входу.
 * На сервері той самий гейт має вимикач (`INTEGRALYK_NUMBER_LINE_FOR_ALL`): вимкнули — сервер знову
 * відповідає лише списку, а дошка чесно показує його відмову словами.
 *
 * Назва функції історична (з часів пілоту) — одне місце гейту для інспектора, картки й Інтегралика.
 */
export function isIntervalsPilotUser(userId: unknown): boolean {
  if (userId === null || userId === undefined || userId === '') return false
  const id = Number(userId)
  return Number.isFinite(id) && id > 0
}
