import { describe, it, expect } from 'vitest'
import { renderPoly, renderTerm, fmtNum } from '../polyText'

/**
 * ⚠️ Навіщо ці тести. Правило «не писати коефіцієнт 1 і нульовий доданок»
 * виглядає очевидним, але в банку задач воно було порушене у ВОСЬМИ темах,
 * і жодна перевірка цього не бачила — дефект помітний лише в готовому
 * тексті. Тому тут зафіксовано саме те, що видно користувачеві.
 */
describe('renderPoly — запис квадратного тричлена', () => {
  it('коефіцієнт 1 не виписують', () => {
    expect(renderPoly([[1, 'x²'], [-1, 'x'], [-6, '']])).toBe('x² − x − 6')
  })

  it('від\'ємна одиниця першою — лишається тільки знак', () => {
    expect(renderPoly([[-1, 'x²'], [3, 'x'], [2, '']])).toBe('−x² + 3x + 2')
  })

  it('нульовий доданок не пишуть узагалі', () => {
    expect(renderPoly([[2, 'x²'], [0, 'x'], [-5, '']])).toBe('2x² − 5')
    expect(renderPoly([[2, 'x²'], [3, 'x'], [0, '']])).toBe('2x² + 3x')
  })

  it('вільний член 1 — це число, а не порожнє місце', () => {
    expect(renderPoly([[1, 'x²'], [0, 'x'], [1, '']])).toBe('x² + 1')
  })

  it('многочлен із самих нулів — це нуль', () => {
    expect(renderPoly([[0, 'x²'], [0, 'x'], [0, '']])).toBe('0')
  })

  it('дробові коефіцієнти — з комою', () => {
    expect(renderPoly([[0.5, 'x²'], [-2.25, '']])).toBe('0,5x² − 2,25')
  })

  it('перший доданок ніколи не починається з «+»', () => {
    expect(renderTerm(5, 'x', true).startsWith('+')).toBe(false)
    expect(renderTerm(5, 'x', false)).toBe(' + 5x')
  })

  it('fmtNum округлює до двох знаків і ставить кому', () => {
    expect(fmtNum(6.25)).toBe('6,25')
    expect(fmtNum(3)).toBe('3')
    expect(fmtNum(1 / 3)).toBe('0,33')
  })
})
