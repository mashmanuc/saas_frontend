/**
 * Обкладинка дошки в «Студії уроків» (власник 2026-10-22: «так, переносимо студію»; макет дизайнера
 * «Студія уроків.html», handoff v2). Дошка без знімка першої сторінки отримує знак і колір замість
 * порожнього прямокутника.
 *
 * Порядок:
 *   1. Слова з назви — масив ПОТОЧНОЇ мови (KEYWORDS[locale]); мови без масиву — пропуск.
 *   2. Монограма: перша літера + число в кінці назви («Почерк7» → «П7»), інакше перші літери двох
 *      слів («Підготовка до НМТ» → «Пд»). Дату не беремо («Вероніка 21.10» → «В»). Будь-яка абетка.
 *   Порожня назва → empty (лише логотип і «Без назви»).
 *
 * Шару «тема з конструктора» (topic_id) з handoff тут немає: список дошок його не віддає.
 * Регулярки — тут, НЕ в i18n: vue-i18n ламає `|`, `{}` і `@`.
 * Колір: картка отримує лише відтінок --h; насиченість і яскравість задає тема (--wb-cover-* у main.css).
 */

export interface BoardCover {
  /** Знак або монограма; порожній рядок, коли назви немає. */
  glyph: string
  /** Відтінок 0–360 для hsl(). */
  hue: number
  /** Монограма (літери назви), а не знак теми. */
  mono: boolean
  /** Назви немає зовсім. */
  empty: boolean
}

type Rule = readonly [RegExp, string, number]

/**
 * Кожне слово — лише з ПОЧАТКУ слова назви: інакше «Матеріали» ловили б «матер», «Нотатки» — «нот»,
 * «Посилання» — «сила». `` тут не годиться: у JS він бачить лише латиницю.
 */
function compile(rules: readonly Rule[]): readonly Rule[] {
  return rules.map(([re, glyph, hue]) => [new RegExp(String.raw`(?<!\p{L})(?:` + re.source + ')', 'iu'), glyph, hue] as const)
}

