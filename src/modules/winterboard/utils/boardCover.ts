/** Слова-підказки за мовою інтерфейсу. Нова мова без масиву просто падає на монограму. */
export const KEYWORDS: Readonly<Record<string, readonly Rule[]>> = { uk: UK, en: EN }

const PREFIX = /^(урок|тема|lesson|topic|lekcja|temat|stunde|thema)\s*[:.—-]?\s*/i
// Назва-заглушка сервера = назви немає: лише логотип, а не монограма «Бн» (макет)
const PLACEHOLDER = /^(без назви|untitled|без названия)$/i
const MONO_HUES = [160, 28, 200, 265, 340, 45, 185, 10] as const
const LETTER = /\p{L}/u

function hash(s: string): number {
  let h = 7
  for (const ch of s) h = (h * 31 + (ch.codePointAt(0) ?? 0)) >>> 0
  return h
}

function firstLetter(word: string | undefined): string {
  return word?.match(LETTER)?.[0] ?? ''
}

export function getBoardCover(name: string | null | undefined, locale: string): BoardCover {
  const raw = (name ?? '').trim()
  const title = PLACEHOLDER.test(raw) ? '' : raw
  const h = hash(title)
  const rules = KEYWORDS[locale.split('-')[0].toLowerCase()] ?? []
  const hit = rules.find(([re]) => re.test(title))
  if (hit) return { glyph: hit[1], hue: hit[2] + ((h % 3) - 1) * 8, mono: false, empty: false }

  const rest = title.replace(PREFIX, '').trim()
  if (!rest) return { glyph: '', hue: 165, mono: true, empty: true }
  let words = rest.split(/\s+/).filter(w => LETTER.test(w))
  if (!words.length) words = title.split(/\s+/).filter(w => LETTER.test(w))
  // Число в кінці, але не хвіст дати чи дробу («21.10», «3/4»)
  const num = rest.match(/(?:^|[^\d.,/-])(\d{1,3})\s*$/)?.[1]
  const first = (firstLetter(words[0]) || '?').toUpperCase()
  const glyph = num ? first + num : first + firstLetter(words[1]).toLowerCase()
  return { glyph, hue: MONO_HUES[h % MONO_HUES.length], mono: true, empty: false }
}
