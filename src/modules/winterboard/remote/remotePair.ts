// WB Remote v1.1: код зв'язки = СТАБІЛЬНИЙ, виводиться з id дошки.
//
// v1 генерував випадковий код при кожному відкритті дошки на ноутбуці, тож
// посилання на телефоні протухало після будь-якого перезавантаження — власник
// уперся в це за 15 хвилин («вийшов з пульта — як повернутись?»).
// Обидва пристрої під одним акаунтом, тож код не є секретом; його роль —
// узгодженість контракту LAW §9 (pair є в кожному повідомленні) і захист від
// вкладки, що лишилась на іншій дошці. Обидва боки рахують його однаково.

export function derivePair(sessionId: string): string {
  const compact = String(sessionId || '').replace(/-/g, '')
  return compact.slice(-6) || '000000'
}
