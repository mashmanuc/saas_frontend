/**
 * «Знайди відео про теорему Піфагора» → «теорему Піфагора» (прототип «відео з
 * пульта», 2026-09-25). Лише явне прохання знайти саме ВІДЕО; інакше null —
 * фраза йде далі звичним шляхом (граматика пульта / Інтегралик на ноутбуці).
 */
const VIDEO_SEARCH_RE = new RegExp(
  '^(?:(?:інтегралику|інтеграліку)[\\s,]+)?(?:будь ласка[\\s,]+)?'
  + '(?:знайди|знайти|пошукай|шукай|покажи)(?:\\s+мені)?\\s+'
  + '(?:відео|відеоролик|ролик)(?:\\s+(?:про|на тему|з теми))?\\s+(.+)$',
  'iu',
)

export function matchVideoSearchPhrase(raw: string): string | null {
  const text = raw.trim().replace(/[.!?…]+$/u, '')
  const query = VIDEO_SEARCH_RE.exec(text)?.[1]?.trim()
  return query && query.length >= 2 ? query : null
}
