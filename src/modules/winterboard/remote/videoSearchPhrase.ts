/**
 * «Знайди відео про теорему Піфагора» → «теорему Піфагора» (прототип «відео з
 * пульта», 2026-09-25). Лише явне прохання знайти чи додати саме ВІДЕО; інакше
 * null — фраза йде далі звичним шляхом (граматика пульта / Інтегралик на ноутбуці).
 *
 * Б-107 (власник 2026-09-27, прод): «додай на дошку відео про смайлика», «додай на
 * дошку відео з Ютуба про смайлика», «додай відео про Степана Бандеру» — усі три
 * пішли до Інтегралика («такого інструмента немає»), бо граматика знала лише
 * «знайди / пошукай / шукай / покажи». Тепер ті самі фрази з «додай / встав / постав»,
 * «на дошку» (до чи після «відео»), «з Ютуба» — і так само відкривають пошук на пульті.
 *
 * Межі, щоб не перехопити чуже:
 *  - «додай / встав / постав» — лише з маркером теми («про», «на тему», «з теми»):
 *    «постав відео на паузу» — не пошук;
 *  - фраза, що ПОЧИНАЄТЬСЯ з «відео про …», — пошук; «відео» десь усередині
 *    (напр. «поясни, що було у відео про клітину») — ні, це до Інтегралика.
 */

const SEP = '[\\s,]+'
const ADDRESS = '(?:(?:інтегралику|інтеграліку)[\\s,]+)?'
const POLITE = '(?:будь[\\s-]ласка[\\s,]+)?'
const MODAL = '(?:(?:можеш|можете|міг би|могла б|могли б|хочу|треба|давай|давайте)[\\s,]+)?'
// Після дієслова: «мені», «нам», «будь ласка» — у будь-якому порядку.
const FILLER = '(?:[\\s,]+(?:мені|нам|будь[\\s-]ласка))*'
const FIND = '(?:знайди|знайдіть|знайти|пошукай|пошукайте|пошукати|шукай|шукайте|покажи|покажіть|показати)'
const ADD = '(?:додай|додайте|додати|встав|вставте|вставити|постав|поставте|поставити)'
const BOARD = '(?:[\\s,]+на\\s+(?:дошку|дошці))?'
const NOUN = '(?:відео|відеоролик|ролик)'
const SOURCE_WORD = '(?:ютуб[ау]?|ютюб[ау]?|ютьюб[ау]?|youtube|you\\s*tube)'
const SOURCE = `(?:[\\s,]+з\\s+${SOURCE_WORD})?`
const TOPIC = '(?:про|на тему|з теми)'

/** «Знайди / покажи відео …»: маркер теми необовʼязковий («покажи відео квадратні рівняння»). */
const FIND_RE = new RegExp(
  `^${ADDRESS}${POLITE}${MODAL}${FIND}${FILLER}${BOARD}${SEP}${NOUN}${BOARD}${SOURCE}(?:${SEP}${TOPIC})?${SEP}(.+)$`,
  'iu',
)
/** «Додай / встав / постав відео …»: лише з маркером теми. */
const ADD_RE = new RegExp(
  `^${ADDRESS}${POLITE}${MODAL}${ADD}${FILLER}${BOARD}${SEP}${NOUN}${BOARD}${SOURCE}${SEP}${TOPIC}${SEP}(.+)$`,
  'iu',
)
/** «Відео про …» без дієслова. */
const BARE_RE = new RegExp(`^${ADDRESS}${POLITE}${NOUN}${SOURCE}${SEP}${TOPIC}${SEP}(.+)$`, 'iu')

/** Хвости, що кажуть «куди» чи «звідки», а не «про що»: «… на дошку», «… з Ютуба». */
const TAIL_RE = new RegExp(`${SEP}(?:на\\s+дошку|на\\s+дошці|з\\s+${SOURCE_WORD})$`, 'iu')

export function matchVideoSearchPhrase(raw: string): string | null {
  const text = raw.trim().replace(/[.!?…]+$/u, '')
  let query = (FIND_RE.exec(text) ?? ADD_RE.exec(text) ?? BARE_RE.exec(text))?.[1]?.trim() ?? ''
  for (let prev = ''; prev !== query;) {
    prev = query
    query = query.replace(TAIL_RE, '').replace(/[\s,]+$/u, '')
  }
  return query.length >= 2 ? query : null
}
