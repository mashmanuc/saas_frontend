/**
 * Автопідгонка висоти картки під її вміст — чисте рішення, без DOM і без стану.
 *
 * Запит власника 2026-09-09: «збільшую шрифт розбору — з'являється скрол, хоча
 * під карткою вільна область». Правильна поведінка, дослівно за рішенням:
 *
 *   1. збільшили шрифт або відкрили розбір;
 *   2. картка спершу росте ЛИШЕ вниз;
 *   3. верхній лівий кут не рухається — учитель не втрачає орієнтир;
 *   4. росте до нижньої межі робочої області полотна;
 *   5. лише коли місця справді немає — вмикається внутрішній скрол.
 *
 * 🔴 «Вільне місце» — це відстань до низу полотна, а НЕ пошук інших об'єктів.
 * Об'єкти на дошці можуть накладатися свідомо, тому вони не мають права
 * блокувати ріст картки. Пряма вимога власника; не «спрощення».
 *
 * Функція нічого не емітить і не пише: вона лише каже, якою має стати висота,
 * або `null`, якщо міняти нічого не треба. Виклик і запис — у WBCanvas, бо
 * там єдине джерело геометрії оверлея і той самий asset, з якого будується
 * Konva-proxy (інакше картка і область захоплення роз'їхались би).
 */

/** Нижче картка стає нечитабельною — не стискаємо сильніше. */
export const AUTO_FIT_MIN_H = 120

/** Різниця, менша за цю, не варта операції: інакше 1 px породжував би запис. */
export const AUTO_FIT_EPSILON = 2

export interface AutoFitInput {
  /** Скільки екранних пікселів треба вмісту (виміряла картка). */
  neededPx: number
  /** Поточний зум полотна: вміст міряється в пікселях, геометрія — в координатах дошки. */
  zoom: number
  /** Верхня межа картки в координатах дошки. */
  y: number
  /** Поточна висота картки в координатах дошки. */
  h: number
  /** Висота полотна — та сама нижня межа робочої області. */
  pageH: number
  /**
   * Висота, яку востаннє поставила автопідгонка (`data.autoFitH`).
   * Якщо вона не збігається з `h`, висоту виставив учитель рукою — і затирати
   * її не можна: від такої висоти дозволено тільки рости.
   */
  lastAutoH?: number
}

/**
 * @returns нова висота картки або `null`, якщо змінювати нічого не треба.
 */
export function nextAutoFitHeight(input: AutoFitInput): number | null {
  const { neededPx, y, h, pageH, lastAutoH } = input
  if (!Number.isFinite(neededPx) || neededPx <= 0) return null

  const zoom = input.zoom > 0 ? input.zoom : 1
  const neededBoard = Math.ceil(neededPx / zoom)

  // Ріст лише вниз: верх (`y`) не рухається, тож стеля — відстань до низу полотна.
  const maxH = Math.max(AUTO_FIT_MIN_H, pageH - y)
  const desired = Math.min(Math.max(neededBoard, AUTO_FIT_MIN_H), maxH)

  const ownedByAutoFit = typeof lastAutoH === 'number' && Math.abs(h - lastAutoH) <= 1
  // Свою висоту автопідгонка має право і стиснути (шрифт зменшили), ручну — ні.
  const next = ownedByAutoFit ? desired : Math.max(h, desired)

  if (Math.abs(next - h) < AUTO_FIT_EPSILON) return null
  return next
}
