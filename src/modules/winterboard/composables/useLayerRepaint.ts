/**
 * Перемалювати шар Konva, коли те, що на ньому намальовано, змінилось.
 *
 * ЧОМУ ЦЕ ІСНУЄ (власник 2026-09-24, P1)
 *
 * Сценарій: виділити об'єкт (PDF/PPT або велику картку) → змінити масштаб
 * дошки → зняти виділення. На аркуші лишались сині лінії й квадратики ручок —
 * «сліди» рамки виділення. Виміряно на проді: після зняття виділення пікселі
 * лишались саме на полотні UI-шару (перевірка `getImageData` по трьох точках
 * ручок), і зникали, щойно шар перемальовувався — подія `resize` або ручний
 * `clearRect` прибирали їх повністю. Тобто об'єктів на шарі вже немає, а
 * старі пікселі не стерті: після зміни масштабу Konva не отримує команди
 * перемалювати шар, на якому щойно зник трансформер.
 *
 * Тут не ховаємо нічого стилями й не чіпаємо саме виділення: лише кажемо
 * Konva перемалювати шар, коли змінилось те, що на ньому має бути.
 */
import { nextTick, watch, type WatchSource } from 'vue'

export interface RepaintableLayer {
  batchDraw?: () => void
}

/**
 * @param getLayer  доступ до Konva-шару (через `ref` компонента vue-konva)
 * @param sources   що саме змінює вміст шару (масштаб, виділення)
 */
export function useLayerRepaint(
  getLayer: () => RepaintableLayer | null | undefined,
  sources: WatchSource[],
): void {
  watch(sources, () => {
    // nextTick: спершу vue-konva прибере/додасть ноди, і вже тоді просимо
    // перемалювати — інакше перемалюємо старий стан.
    void nextTick(() => {
      try {
        getLayer()?.batchDraw?.()
      } catch (error) {
        console.warn('[WB:Canvas] layer repaint failed', error)
      }
    })
  })
}
