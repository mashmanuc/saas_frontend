/** Плоский список усіх статей (для пошуку за slug). */
export const ALL_HELP_ARTICLES: HelpArticle[] = HELP_SECTIONS.flatMap((s) => s.articles)

/** Перша стаття (дефолт, коли slug не вказано). */
export const DEFAULT_HELP_SLUG = HELP_SECTIONS[0].articles[0].slug

/** Знайти статтю + її секцію за slug. */
export function findHelpArticle(slug: string): { section: HelpSection; article: HelpArticle } | null {
  for (const section of HELP_SECTIONS) {
    const article = section.articles.find((a) => a.slug === slug)
    if (article) return { section, article }
  }
  return null
}
